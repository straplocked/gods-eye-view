/** Positions by upper-case ISO code, each a frozen `[longitude, latitude]`. */
export const COUNTRY_CENTROIDS = Object.freeze(
  Object.fromEntries(
    Object.entries(POSITIONS).map(([code, position]) => [
      code,
      Object.freeze(position),
    ]),
  ),
);

/**
 * The marker position of a country.
 * @param {string} code - ISO 3166-1 alpha-2 code, any case.
 * @returns {?[number, number]} `[longitude, latitude]`, or null for a code with no position.
 */
export function countryCentroid(code) {
  if (typeof code !== 'string') return null;
  const key = code.trim().toUpperCase();
  return Object.hasOwn(COUNTRY_CENTROIDS, key) ? COUNTRY_CENTROIDS[key] : null;
}
